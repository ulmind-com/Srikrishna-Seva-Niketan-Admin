/**
 * Standard Levenshtein distance for fuzzy OCR matching.
 */
function levenshtein(a: string, b: string): number {
  const m = a.length;
  const n = b.length;
  if (m === 0) return n;
  if (n === 0) return m;

  if (m > n) return levenshtein(b, a);

  let prev = Array.from({ length: m + 1 }, (_, i) => i);
  let curr = new Array<number>(m + 1);

  for (let j = 1; j <= n; j++) {
    curr[0] = j;
    const bChar = b[j - 1];
    for (let i = 1; i <= m; i++) {
      const cost = a[i - 1] === bChar ? 0 : 1;
      curr[i] = Math.min(
        curr[i - 1] + 1,
        prev[i] + 1,
        prev[i - 1] + cost
      );
    }
    const temp = prev;
    prev = curr;
    curr = temp;
  }

  return prev[m];
}

/**
 * Clean and normalize a string to alphanumeric characters only.
 */
function normalizeAlphaNum(str: string): string {
  return str.toLowerCase().replace(/[^a-z0-9]/g, "");
}

/**
 * Extract meaningful name tokens from an applicant's full name.
 */
function extractNameTokens(fullName: string): string[] {
  return fullName
    .toLowerCase()
    .replace(/[^a-z\s]/g, " ")
    .split(/\s+/)
    .filter((token) => token.length > 0 && !SALUTATIONS.has(token));
}

/**
 * Preprocess image on an offscreen HTML Canvas:
 * Converts to high-contrast grayscale and normalizes resolution for optimal Tesseract OCR.
 */
async function preprocessImageForOcr(file: File | Blob): Promise<Blob> {
  if (typeof window === "undefined" || typeof document === "undefined") {
    return file;
  }

  // If not image (e.g. PDF), return original
  if (file instanceof File && file.type && !file.type.startsWith("image/")) {
    return file;
  }

  return new Promise((resolve) => {
    const img = new Image();
    const url = URL.createObjectURL(file);

    img.onload = () => {
      URL.revokeObjectURL(url);
      try {
        const canvas = document.createElement("canvas");
        const ctx = canvas.getContext("2d", { willReadFrequently: true });
        if (!ctx) {
          resolve(file);
          return;
        }

        let targetWidth = img.naturalWidth || img.width;
        let targetHeight = img.naturalHeight || img.height;

        // Scale image to standard OCR width (1400-1800px)
        if (targetWidth < 1200) {
          const scale = 1400 / targetWidth;
          targetWidth = 1400;
          targetHeight = Math.round(targetHeight * scale);
        } else if (targetWidth > 2200) {
          const scale = 2000 / targetWidth;
          targetWidth = 2000;
          targetHeight = Math.round(targetHeight * scale);
        }

        canvas.width = targetWidth;
        canvas.height = targetHeight;
        ctx.drawImage(img, 0, 0, targetWidth, targetHeight);

        const imageData = ctx.getImageData(0, 0, targetWidth, targetHeight);
        const data = imageData.data;
        const len = data.length;

        // Calculate average brightness
        let sumLuminance = 0;
        let samples = 0;
        for (let i = 0; i < len; i += 40) {
          sumLuminance += 0.299 * data[i] + 0.587 * data[i + 1] + 0.114 * data[i + 2];
          samples++;
        }
        const avgLum = samples > 0 ? sumLuminance / samples : 128;

        // Boost contrast and binarize text against colored card backgrounds
        for (let i = 0; i < len; i += 4) {
          const gray = 0.299 * data[i] + 0.587 * data[i + 1] + 0.114 * data[i + 2];
          let val = (gray - avgLum) * 1.6 + avgLum;
          if (val < 115) val = 0;
          else if (val > 155) val = 255;

          data[i] = val;
          data[i + 1] = val;
          data[i + 2] = val;
        }

        ctx.putImageData(imageData, 0, 0);

        canvas.toBlob(
          (blob) => {
            resolve(blob || file);
          },
          "image/png",
          0.95
        );
      } catch (err) {
        console.warn("Canvas preprocessing error, using raw file:", err);
        resolve(file);
      }
    };

    img.onerror = () => {
      URL.revokeObjectURL(url);
      resolve(file);
    };

    img.src = url;
  });
}

/**
 * Check if a single name token matches any word in the OCR word list.
 * Exact word match, or Levenshtein <= 1 for tokens of length >= 4.
 * CRITICAL: Never matches substrings (e.g. "Roy" will NEVER match "Royal", "Ali" will NEVER match "Nationality").
 */
function matchesWord(token: string, ocrWords: string[]): boolean {
  for (const word of ocrWords) {
    if (word === token) return true;

    // For tokens of length >= 4, allow 1 minor OCR typo (e.g. '0' vs 'O', '1' vs 'I', 'rn' vs 'm')
    if (token.length >= 4 && Math.abs(word.length - token.length) <= 1) {
      if (levenshtein(word, token) <= 1) {
        return true;
      }
    }
  }
  return false;
}

/**
 * Comprehensive verification of government documents:
 * 1. Preprocesses image on Canvas.
 * 2. Runs Tesseract OCR text recognition.
 * 3. Strict token & word-boundary name matching (requires First Name AND Last Name match).
 * 4. ID Number verification (Aadhaar / PAN / Voter ID).
 * 5. Internet download, Google search sample, and stock watermark fraud detection.
 */
export async function verifyDocument({
  file,
  idType,
  idNumber,
  applicantName,
  applicantPhotoUrl,
}: VerifyDocumentOptions): Promise<VerificationResult> {
  const fraudFlags: string[] = [];
  const normalizedEnteredId = normalizeAlphaNum(idNumber);
  const nameTokens = extractNameTokens(applicantName);

  // 1. File inspection: check file name for suspicious download markers
  if (file instanceof File) {
    const lowerFileName = file.name.toLowerCase();
    for (const susp of SUSPICIOUS_FILENAME_KEYWORDS) {
      if (lowerFileName.includes(susp)) {
        fraudFlags.push(
          `Uploaded file name indicates an internet sample or stock download ("${file.name}")`
        );
        break;
      }
    }

    // Check file size (suspicious thumbnail if < 15KB)
    if (file.size < 15 * 1024) {
      fraudFlags.push("Image file size is suspiciously small (low-resolution internet thumbnail)");
    }
  }

  // 2. Preprocess image & run OCR text recognition
  let extractedText = "";
  try {
    const ocrBlob = await preprocessImageForOcr(file);
    const worker = await createWorker("eng");
    const ret = await worker.recognize(ocrBlob);
    extractedText = ret.data.text || "";
    await worker.terminate();

    // If preprocessed OCR returned very short text, try raw file as fallback
    if (extractedText.replace(/\s+/g, "").length < 25 && ocrBlob !== file) {
      try {
        const rawWorker = await createWorker("eng");
        const rawRet = await rawWorker.recognize(file);
        const rawText = rawRet.data.text || "";
        await rawWorker.terminate();
        if (rawText.replace(/\s+/g, "").length > extractedText.replace(/\s+/g, "").length) {
          extractedText = rawText;
        }
      } catch {
        // keep preprocessed text
      }
    }
  } catch (err) {
    console.warn("OCR recognition encountered an error:", err);
    extractedText = "";
  }

  const normalizedOcr = normalizeAlphaNum(extractedText);
  const lowerOcr = extractedText.toLowerCase();

  // Extract individual words from OCR text (clean words without punctuation)
  const ocrWords = lowerOcr
    .replace(/[^a-z0-9\s]/g, " ")
    .split(/\s+/)
    .filter((w) => w.length > 0);

  // 3. Check for unreadable / blurred document
  // CRITICAL: NEVER give benefit of doubt! If text cannot be read, verification MUST fail!
  if (normalizedOcr.length < 25) {
    fraudFlags.push(
      "Unable to read document text. Please upload a clear, high-resolution original document scan (not a blurred photo or thumbnail)."
    );
    return {
      isVerified: false,
      confidenceScore: 10,
      idNumberMatched: false,
      nameMatched: false,
      photoMatched: false,
      fraudRisk: "high",
      fraudFlags,
      extractedText: extractedText.slice(0, 500),
      summary: "Verification failed: Document text is unreadable or image is blurred.",
      verifiedAt: new Date().toISOString(),
    };
  }

  // 4. Check for Stock / AI / Sample Fraud Watermarks
  for (const kw of FRAUD_KEYWORDS) {
    // Word boundary or phrase search to avoid partial syllable matches
    const kwRegex = new RegExp(`\\b${kw.replace(/[-\s]/g, "[-\\s]")}\\b`, "i");
    if (kwRegex.test(extractedText)) {
      fraudFlags.push(`Watermark or stock template keyword detected on document: "${kw}"`);
    }
  }

  // 5. Check for known sample names on Google cards (e.g. "Anuradha Roy", "Sunil Kumar")
  const normalizedApplicantName = applicantName.toLowerCase().trim();
  for (const sampleName of KNOWN_SAMPLE_NAMES) {
    if (!normalizedApplicantName.includes(sampleName) && lowerOcr.includes(sampleName)) {
      fraudFlags.push(
        `Document contains a known internet sample template identity: "${sampleName}"`
      );
    }
  }

  // 6. Check for known dummy ID numbers
  for (const dummyId of KNOWN_DUMMY_IDS) {
    if (dummyId !== normalizedEnteredId && normalizedOcr.includes(dummyId.toLowerCase())) {
      fraudFlags.push(
        `Document contains a well-known sample/dummy ID number used in online templates (${dummyId})`
      );
    }
  }

  // 7. ID Number Matching Algorithm
  let idNumberMatched = false;

  if (normalizedEnteredId.length >= 4) {
    if (normalizedOcr.includes(normalizedEnteredId)) {
      idNumberMatched = true;
    } else {
      // Check for partial / masked Aadhaar (e.g. XXXX XXXX 1234 or last 4 digits)
      const lastFour = normalizedEnteredId.slice(-4);
      const isAadhaar = idType.toLowerCase().includes("aadhaar");

      if (isAadhaar) {
        // If it's Aadhaar, check if the document contains Aadhaar markers
        const hasAadhaarKeywords =
          lowerOcr.includes("aadhaar") ||
          lowerOcr.includes("uidai") ||
          lowerOcr.includes("government of india") ||
          lowerOcr.includes("unique identification");

        if (hasAadhaarKeywords && normalizedOcr.includes(lastFour)) {
          // Check if there is another 12-digit number on the card that contradicts the entered ID
          const twelveDigitNumbers = extractedText.replace(/[^0-9]/g, "").match(/\d{12}/g) || [];
          const contradictingNumber = twelveDigitNumbers.find(
            (num) => num !== normalizedEnteredId
          );

          if (contradictingNumber) {
            fraudFlags.push(
              `ID number mismatch: Document contains a different Aadhaar number (${contradictingNumber}) than entered (${idNumber})`
            );
            idNumberMatched = false;
          } else {
            idNumberMatched = true;
          }
        }
      }
    }
  }

  if (!idNumberMatched) {
    fraudFlags.push(
      `The entered ${idType} number (${idNumber}) was not found on the uploaded document`
    );
  }

  // 8. Strict Name Matching Algorithm
  let nameMatched = false;

  if (nameTokens.length === 0) {
    nameMatched = false;
    fraudFlags.push("Applicant name is empty or invalid.");
  } else if (nameTokens.length === 1) {
    // Single name: must match exactly an OCR word
    nameMatched = matchesWord(nameTokens[0], ocrWords);
    if (!nameMatched) {
      fraudFlags.push(
        `Applicant name "${applicantName}" was not found on the uploaded document`
      );
    }
  } else {
    // Multi-token name (e.g. First Name + Surname)
    const firstName = nameTokens[0];
    const lastName = nameTokens[nameTokens.length - 1];

    const firstNameMatched = matchesWord(firstName, ocrWords);
    const lastNameMatched = matchesWord(lastName, ocrWords);

    // Count how many tokens matched
    let matchedCount = 0;
    for (const token of nameTokens) {
      if (matchesWord(token, ocrWords)) {
        matchedCount++;
      }
    }

    if (nameTokens.length === 2) {
      // For First + Last Name: BOTH MUST MATCH!
      // If only one matches (e.g. only "Sharma" or only "Suresh"), it is a mismatch!
      if (firstNameMatched && lastNameMatched) {
        nameMatched = true;
      } else if (firstNameMatched && !lastNameMatched) {
        fraudFlags.push(
          `Surname mismatch: Document does not match surname "${lastName}" in "${applicantName}"`
        );
      } else if (!firstNameMatched && lastNameMatched) {
        fraudFlags.push(
          `First name mismatch: Document does not match first name "${firstName}" in "${applicantName}"`
        );
      } else {
        fraudFlags.push(
          `Applicant name "${applicantName}" does not match the name on the uploaded document`
        );
      }
    } else {
      // 3 or more tokens: e.g. "Arnab Kumar Senapati"
      // Primary rule: First Name AND Last Name must both match,
      // OR at least 70% of tokens match with at least one non-filler token matching.
      if (firstNameMatched && lastNameMatched) {
        nameMatched = true;
      } else if (matchedCount >= 2 && (firstNameMatched || lastNameMatched)) {
        // Middle name + either first or last name
        nameMatched = true;
      } else {
        const onlyFillerMatched = nameTokens.some(
          (t) => COMMON_FILLER_TOKENS.has(t) && matchesWord(t, ocrWords)
        );
        if (onlyFillerMatched) {
          fraudFlags.push(
            `Generic name match only: Only a common middle name token matched. Primary identity does not match "${applicantName}".`
          );
        } else {
          fraudFlags.push(
            `Applicant name "${applicantName}" does not match the identity on the uploaded document`
          );
        }
      }
    }
  }

  // 9. Photo / Face check heuristic
  let photoMatched = true;
  if (applicantPhotoUrl) {
    const lowerPhoto = applicantPhotoUrl.toLowerCase();
    if (lowerPhoto.includes("qr") || lowerPhoto.includes("icon") || lowerPhoto.includes("vector")) {
      photoMatched = false;
      fraudFlags.push("Self-photo appears to be a QR code or graphic instead of a face photo");
    }
  }

  // 10. Calculate overall confidence and fraud risk
  let confidenceScore = 0;
  if (idNumberMatched) confidenceScore += 50;
  if (nameMatched) confidenceScore += 35;
  if (photoMatched) confidenceScore += 15;

  if (fraudFlags.length > 0) {
    confidenceScore = Math.max(0, confidenceScore - fraudFlags.length * 30);
  }

  // Determine Fraud Risk
  // High risk if: any fraud flags exist, OR name mismatched, OR ID mismatched
  const fraudRisk: "low" | "medium" | "high" =
    fraudFlags.length > 0 || !nameMatched || !idNumberMatched || confidenceScore < 60
      ? "high"
      : confidenceScore < 80
      ? "medium"
      : "low";

  // Document is ONLY verified if fraud risk is low and BOTH ID and name are matched!
  const isVerified = fraudRisk === "low" && idNumberMatched && nameMatched;

  const summary = isVerified
    ? `Document verified successfully. ${idType} number and applicant name verified against original document text.`
    : `Verification warning: ${fraudFlags.join(". ") || "Data mismatch detected."}`;

  return {
    isVerified,
    confidenceScore: Math.min(100, Math.round(confidenceScore)),
    idNumberMatched,
    nameMatched,
    photoMatched,
    fraudRisk,
    fraudFlags,
    extractedText: extractedText.slice(0, 500),
    summary,
    verifiedAt: new Date().toISOString(),
  };
}
